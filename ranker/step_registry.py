"""Small, inspectable registry of step output paths and named artifacts.

``StepDefinition`` intentionally does not encode a dependency graph.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from types import MappingProxyType


@dataclass(frozen=True)
class StepDefinition:
    key: str
    output_dir: Path
    artifacts: Mapping[str, str]

    def artifact_name(self, key: str) -> str:
        return self.artifacts[key]

    def artifact(self, key: str) -> Path:
        return self.output_dir / self.artifact_name(key)


def _step(key: str, directory: str, **artifacts: str) -> StepDefinition:
    names = list(artifacts.values())
    if len(names) != len(set(names)) or any(Path(name).is_absolute() for name in names):
        raise ValueError(f"Invalid artifact registry entry for {key}.")
    return StepDefinition(
        key=key,
        output_dir=Path(directory),
        artifacts=MappingProxyType(dict(artifacts)),
    )


